'use strict';

// Turns one or more SQL Server ShowPlan XML documents into a flat list of
// operator rows - the data behind the "Top Operations" tabular view that
// sits next to the graphical plan (see queryResultsGrid.js). The graphical
// plan is drawn by html-query-plan, which already parses this same XML with
// the browser's DOMParser; this module instead uses its own tiny XML reader
// (same technique as database/miniXml.js) so the parsing - and this file's
// tests - don't depend on a DOM being present.

// === A tiny XML reader (element: { name, attributes, children, text }) ===
// Showplan XML is machine-generated by SQL Server, never user-supplied, so
// unlike database/miniXml.js this skips the defensive size/depth limits and
// strict error messages that file needs for untrusted files.

const XML_NAMED_ENTITIES = { lt: '<', gt: '>', quot: '"', apos: "'", amp: '&' };

function xmlDecode(text) {
    return text.replace(/&(?:#(\d+)|#x([0-9a-fA-F]+)|(lt|gt|quot|apos|amp));/g, (match, dec, hex, name) => {
        if (name) return XML_NAMED_ENTITIES[name];
        const code = dec !== undefined ? Number(dec) : parseInt(hex, 16);
        return Number.isInteger(code) && code >= 0 && code <= 0x10FFFF ? String.fromCodePoint(code) : match;
    });
}

function parseXmlAttributes(text) {
    const attributes = {};
    for (const m of text.matchAll(/([^\s=]+)\s*=\s*(?:"([^"]*)"|'([^']*)')/g)) {
        attributes[m[1]] = xmlDecode(m[2] !== undefined ? m[2] : m[3]);
    }
    return attributes;
}

function parseXmlTree(source) {
    // Groups: 1 CDATA, 2 closing tag name, 3 opening tag name, 4 its attributes, 5 self-close slash, 6 text.
    const token = /<!--[\s\S]*?-->|<!\[CDATA\[([\s\S]*?)\]\]>|<\?[\s\S]*?\?>|<\/([^\s>]+)\s*>|<([^\s/>!?]+)((?:\s+[^\s=/>]+\s*=\s*(?:"[^"]*"|'[^']*'))*)\s*(\/?)>|([^<]+)/g;
    const top = { name: '#document', attributes: {}, children: [], text: '' };
    const stack = [top];
    let match;
    while ((match = token.exec(source))) {
        const current = stack[stack.length - 1];
        if (match[1] !== undefined) {
            current.text += match[1]; // CDATA
        } else if (match[2] !== undefined) {
            if (stack.length > 1) stack.pop(); // closing tag
        } else if (match[3] !== undefined) {
            const element = { name: match[3], attributes: parseXmlAttributes(match[4] || ''), children: [], text: '' };
            current.children.push(element);
            if (!match[5]) stack.push(element);
        } else if (match[6] !== undefined) {
            current.text += xmlDecode(match[6]);
        }
    }
    return top.children[0] || null;
}

// Direct children called `name`.
function childrenNamed(element, name) {
    return element.children.filter(child => child.name === name);
}

// Every `name` descendant, not crossing into a nested RelOp - the RelOp
// children of a Hash/NestedLoops/etc. node own their own Object, Warnings
// and RunTimeInformation; they must not be attributed to their parent.
function ownDescendants(element, name) {
    const result = [];
    (function walk(node) {
        node.children.forEach(child => {
            if (child.name === name) result.push(child);
            if (child.name !== 'RelOp') walk(child);
        });
    })(element);
    return result;
}

// The RelOp elements that are this operator's direct inputs in the plan
// tree - nested one or more wrapper elements down (e.g. RelOp > NestedLoops >
// RelOp), never found by looking at `.children` alone.
function directChildRelOps(relOp) {
    const result = [];
    (function walk(node) {
        node.children.forEach(child => {
            if (child.name === 'RelOp') result.push(child);
            else walk(child);
        });
    })(relOp);
    return result;
}

function stripBrackets(name) {
    return name.replace(/^\[/, '').replace(/\]$/, '');
}

function formatObject(objectEl) {
    const a = objectEl.attributes;
    const parts = [a.Schema, a.Table].filter(Boolean).map(stripBrackets);
    let text = parts.join('.');
    if (a.Index) text += ` (${stripBrackets(a.Index)})`;
    return text;
}

// "NoJoinPredicate" -> "No join predicate"; unmapped types still get a
// readable label instead of disappearing when SQL Server adds a new one.
const WARNING_LABELS = {
    NoJoinPredicate: 'No join predicate',
    SpillToTempDb: 'Spilled to tempdb',
    ColumnsWithNoStatistics: 'Columns with no statistics',
    PlanAffectingConvert: 'Implicit conversion affecting plan',
    WaitStats: 'Significant wait',
    MemoryGrantWarning: 'Memory grant adjusted at runtime'
};

function warningLabel(name) {
    return WARNING_LABELS[name] || name.replace(/([a-z])([A-Z])/g, '$1 $2').replace(/^./, c => c.toUpperCase());
}

function numberAttr(attributes, name) {
    return attributes[name] !== undefined ? Number(attributes[name]) : null;
}

// One row per RelOp under `stmt`, each carrying enough to locate the matching
// node in the graphical plan (see queryResultsGrid.js's syncPlanDiagramNode).
function buildRow(relOp, depth, planIndex, stmt, totalCost) {
    const attrs = relOp.attributes;
    const childRelOps = directChildRelOps(relOp);
    const childCostSum = childRelOps.reduce((sum, child) => sum + (numberAttr(child.attributes, 'EstimatedTotalSubtreeCost') || 0), 0);
    const subtreeCost = numberAttr(attrs, 'EstimatedTotalSubtreeCost') || 0;
    // Same formula as html-query-plan's own "Cost: X%" node label (qp.xslt,
    // EstimatedOperatorCost): this operator's own cost, not its subtree's.
    const selfCost = Math.max(0, subtreeCost - childCostSum);
    const costPercent = totalCost > 0 ? (selfCost / totalCost) * 100 : 0;

    const object = ownDescendants(relOp, 'Object').map(formatObject).filter(Boolean).join(', ');
    const warningsEl = ownDescendants(relOp, 'Warnings')[0];
    const warnings = warningsEl ? warningsEl.children.map(c => warningLabel(c.name)) : [];

    const threads = ownDescendants(relOp, 'RunTimeCountersPerThread');
    const hasActual = threads.length > 0;
    const sumThreadAttr = name => threads.reduce((sum, t) => sum + (numberAttr(t.attributes, name) || 0), 0);

    const physicalOp = attrs.PhysicalOp || attrs.LogicalOp || '';
    const logicalOp = attrs.LogicalOp || '';

    return {
        planIndex,
        statementId: stmt.attributes.StatementId || '',
        statementText: stmt.attributes.StatementText || '',
        nodeId: attrs.NodeId || '',
        depth,
        physicalOp,
        logicalOp: logicalOp !== physicalOp ? logicalOp : '',
        object,
        estimatedRows: numberAttr(attrs, 'EstimateRows'),
        actualRows: hasActual ? sumThreadAttr('ActualRows') : null,
        actualExecutions: hasActual ? sumThreadAttr('ActualExecutions') : null,
        subtreeCost,
        costPercent,
        avgRowSize: numberAttr(attrs, 'AvgRowSize'),
        parallel: attrs.Parallel === 'true' || attrs.Parallel === '1',
        warnings
    };
}

// Every StatementId-bearing element with a QueryPlan - covers top-level
// statements and (for free, by recursing everywhere) statements nested
// inside an EXEC'd stored procedure's own captured plan.
function collectStatements(element, out) {
    if (element.attributes.StatementId && childrenNamed(element, 'QueryPlan').length) out.push(element);
    element.children.forEach(child => collectStatements(child, out));
}

class QueryPlanAnalyzer {
    // planXmls: the raw ShowPlan XML strings QueryHandlers.js sends (one per
    // batch). A batch that fails to parse just contributes no rows - the
    // graphical plan already shows its own per-plan parse error.
    static analyze(planXmls) {
        const rows = [];
        let hasActual = false;
        let statementCount = 0;

        (planXmls || []).forEach((xmlText, planIndex) => {
            let root;
            try { root = parseXmlTree(xmlText); } catch { return; }
            if (!root) return;

            const statements = [];
            collectStatements(root, statements);
            statements.forEach(stmt => {
                statementCount++;
                const queryPlan = childrenNamed(stmt, 'QueryPlan')[0];
                const rootRelOp = queryPlan && childrenNamed(queryPlan, 'RelOp')[0];
                if (!rootRelOp) return;
                const totalCost = numberAttr(rootRelOp.attributes, 'EstimatedTotalSubtreeCost') || 0;

                (function walk(relOp, depth) {
                    const row = buildRow(relOp, depth, planIndex, stmt, totalCost);
                    rows.push(row);
                    if (row.actualRows !== null) hasActual = true;
                    directChildRelOps(relOp).forEach(child => walk(child, depth + 1));
                })(rootRelOp, 0);
            });
        });

        return { rows, hasActual, multiStatement: statementCount > 1 };
    }
}

if (typeof module !== 'undefined' && module.exports) {
    module.exports = QueryPlanAnalyzer;
}
